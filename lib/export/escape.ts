/**
 * Pure string HTML escape — safe in workers, Node tests, and the browser
 * (no DOM dependency, unlike the old document.createElement approach).
 */
export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
